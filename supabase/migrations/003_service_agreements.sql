-- 003_service_agreements.sql
-- Phase 3a: maintenance (service) agreements with schedule parts, planned visits and pricing.
--
-- 1. service_types and service_tasks: lists edited on /settings. Deactivated rather
--    than deleted, so old agreements keep their labels. Seeded only while empty, so a
--    re-run never brings back a renamed or removed entry.
-- 2. service_agreements: one per client (optionally per property) and service type.
-- 3. agreement_schedule_parts: date range + every N weeks + price per visit.
-- 4. agreement_tasks: which tasks an agreement includes.
-- 5. agreement_visits: the planned dates, generated by the app from the parts.
-- 6. save_service_agreement(): writes an agreement and all its parts, tasks and
--    visits in one transaction, so a failed save never leaves half an agreement.
--
-- Safe to re-run: every step checks whether it has already been done.

begin;

-- 1. Settings lists ------------------------------------------------------------
create table if not exists public.service_types (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  -- Default season (months 1-12). Both set, or both empty. End before start
  -- (e.g. 10 -> 1) means the season crosses into the next year.
  default_start_month smallint,
  default_end_month smallint,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint service_types_name_check check (btrim(name) <> ''),
  constraint service_types_season_check check (
    (default_start_month is null and default_end_month is null)
    or (default_start_month between 1 and 12 and default_end_month between 1 and 12)
  )
);

create unique index if not exists service_types_name_key
  on public.service_types (lower(btrim(name)));

insert into public.service_types (name, default_start_month, default_end_month, sort_order)
select v.name, v.start_month, v.end_month, v.sort_order
from (values
  ('Lawn care', 3::smallint, 10::smallint, 1),
  ('Leaf cleanup', 10::smallint, 1::smallint, 2),
  ('Winter tidying', null, null, 3),
  ('Other', null, null, 4)
) as v(name, start_month, end_month, sort_order)
where not exists (select 1 from public.service_types);

create table if not exists public.service_tasks (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint service_tasks_name_check check (btrim(name) <> '')
);

create unique index if not exists service_tasks_name_key
  on public.service_tasks (lower(btrim(name)));

insert into public.service_tasks (name, sort_order)
select v.name, v.sort_order
from (values ('Mowing', 1), ('Edging', 2), ('Trimming', 3), ('Blowing', 4)) as v(name, sort_order)
where not exists (select 1 from public.service_tasks);

-- 2. Agreements ------------------------------------------------------------------
-- Allowed values match lib/agreements/constants.ts.
create table if not exists public.service_agreements (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.clients (id),
  property_id uuid references public.properties (id),
  service_type_id uuid not null references public.service_types (id),
  billing_type text not null
    constraint service_agreements_billing_type_check
    check (billing_type in ('flat_monthly', 'per_visit')),
  status text not null default 'draft'
    constraint service_agreements_status_check
    check (status in ('draft', 'active', 'ended')),
  -- The term. end_date is the last day service is provided.
  start_date date not null,
  end_date date not null,
  -- Flat monthly only: total of the planned visits / billing_months, in whole dollars.
  billing_months integer,
  monthly_price numeric(10, 2),
  -- Per-visit agreements with no schedule (on call) only.
  price_per_visit numeric(10, 2),
  service_areas text,
  notes text,
  renewed_from_id uuid references public.service_agreements (id) on delete set null,
  created_at timestamptz not null default now(),
  constraint service_agreements_dates_check check (end_date >= start_date),
  constraint service_agreements_billing_months_check
    check (billing_months is null or billing_months > 0),
  constraint service_agreements_prices_check check (
    (monthly_price is null or monthly_price >= 0)
    and (price_per_visit is null or price_per_visit >= 0)
  ),
  constraint service_agreements_flat_monthly_check check (
    case billing_type
      when 'flat_monthly' then
        billing_months is not null and monthly_price is not null and price_per_visit is null
      else billing_months is null and monthly_price is null
    end
  )
);

create index if not exists service_agreements_client_id_idx
  on public.service_agreements (client_id);

-- 3. Schedule parts --------------------------------------------------------------
-- Visits fall on start_date, then every interval_weeks weeks up to end_date.
create table if not exists public.agreement_schedule_parts (
  id uuid primary key default gen_random_uuid(),
  agreement_id uuid not null references public.service_agreements (id) on delete cascade,
  start_date date not null,
  end_date date not null,
  interval_weeks smallint not null
    constraint agreement_schedule_parts_interval_check check (interval_weeks between 1 and 4),
  price_per_visit numeric(10, 2) not null
    constraint agreement_schedule_parts_price_check check (price_per_visit >= 0),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint agreement_schedule_parts_dates_check check (end_date >= start_date)
);

create index if not exists agreement_schedule_parts_agreement_id_idx
  on public.agreement_schedule_parts (agreement_id);

-- 4. Tasks included ----------------------------------------------------------------
create table if not exists public.agreement_tasks (
  agreement_id uuid not null references public.service_agreements (id) on delete cascade,
  task_id uuid not null references public.service_tasks (id),
  primary key (agreement_id, task_id)
);

-- 5. Planned visits ----------------------------------------------------------------
-- schedule_part_id is null for a date added by hand.
create table if not exists public.agreement_visits (
  id uuid primary key default gen_random_uuid(),
  agreement_id uuid not null references public.service_agreements (id) on delete cascade,
  schedule_part_id uuid references public.agreement_schedule_parts (id) on delete set null,
  visit_date date not null,
  price numeric(10, 2) not null
    constraint agreement_visits_price_check check (price >= 0),
  created_at timestamptz not null default now(),
  constraint agreement_visits_agreement_date_key unique (agreement_id, visit_date)
);

-- The app reads and writes with the service-role key, which bypasses RLS.
-- With RLS on and no policies, the public anon key cannot read or change these.
alter table public.service_types enable row level security;
alter table public.service_tasks enable row level security;
alter table public.service_agreements enable row level security;
alter table public.agreement_schedule_parts enable row level security;
alter table public.agreement_tasks enable row level security;
alter table public.agreement_visits enable row level security;

-- 6. Save in one transaction -------------------------------------------------------
-- p_id null creates an agreement; otherwise updates it and replaces its parts, tasks
-- and visits. Each visit names its part by position in p_parts ("part_index"), or
-- null for a date added by hand. The app validates everything first; the table
-- constraints above are the backstop.
create or replace function public.save_service_agreement(
  p_id uuid,
  p_agreement jsonb,
  p_parts jsonb,
  p_task_ids uuid[],
  p_visits jsonb
) returns uuid
language plpgsql
set search_path = ''
as $$
declare
  v_id uuid := p_id;
begin
  if v_id is null then
    insert into public.service_agreements (
      client_id, property_id, service_type_id, billing_type, status, start_date, end_date,
      billing_months, monthly_price, price_per_visit, service_areas, notes, renewed_from_id
    ) values (
      (p_agreement->>'client_id')::uuid,
      (p_agreement->>'property_id')::uuid,
      (p_agreement->>'service_type_id')::uuid,
      p_agreement->>'billing_type',
      p_agreement->>'status',
      (p_agreement->>'start_date')::date,
      (p_agreement->>'end_date')::date,
      (p_agreement->>'billing_months')::integer,
      (p_agreement->>'monthly_price')::numeric,
      (p_agreement->>'price_per_visit')::numeric,
      p_agreement->>'service_areas',
      p_agreement->>'notes',
      (p_agreement->>'renewed_from_id')::uuid
    )
    returning id into v_id;
  else
    update public.service_agreements set
      property_id = (p_agreement->>'property_id')::uuid,
      service_type_id = (p_agreement->>'service_type_id')::uuid,
      billing_type = p_agreement->>'billing_type',
      status = p_agreement->>'status',
      start_date = (p_agreement->>'start_date')::date,
      end_date = (p_agreement->>'end_date')::date,
      billing_months = (p_agreement->>'billing_months')::integer,
      monthly_price = (p_agreement->>'monthly_price')::numeric,
      price_per_visit = (p_agreement->>'price_per_visit')::numeric,
      service_areas = p_agreement->>'service_areas',
      notes = p_agreement->>'notes'
    where id = v_id;

    if not found then
      raise exception 'Service agreement % not found', v_id;
    end if;

    delete from public.agreement_visits where agreement_id = v_id;
    delete from public.agreement_schedule_parts where agreement_id = v_id;
    delete from public.agreement_tasks where agreement_id = v_id;
  end if;

  insert into public.agreement_schedule_parts (
    agreement_id, start_date, end_date, interval_weeks, price_per_visit, sort_order
  )
  select
    v_id,
    (p->>'start_date')::date,
    (p->>'end_date')::date,
    (p->>'interval_weeks')::smallint,
    (p->>'price_per_visit')::numeric,
    (ord - 1)::integer
  from jsonb_array_elements(coalesce(p_parts, '[]'::jsonb)) with ordinality as t(p, ord);

  insert into public.agreement_tasks (agreement_id, task_id)
  select distinct v_id, task_id
  from unnest(coalesce(p_task_ids, '{}'::uuid[])) as t(task_id);

  insert into public.agreement_visits (agreement_id, schedule_part_id, visit_date, price)
  select v_id, sp.id, (v->>'visit_date')::date, (v->>'price')::numeric
  from jsonb_array_elements(coalesce(p_visits, '[]'::jsonb)) as t(v)
  left join public.agreement_schedule_parts sp
    on sp.agreement_id = v_id
   and sp.sort_order = (v->>'part_index')::integer;

  return v_id;
end;
$$;

-- Only the app (service role) may call it.
revoke execute on function public.save_service_agreement(uuid, jsonb, jsonb, uuid[], jsonb)
  from public, anon, authenticated;
grant execute on function public.save_service_agreement(uuid, jsonb, jsonb, uuid[], jsonb)
  to service_role;

commit;
